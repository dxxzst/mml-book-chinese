with open('4.Index.md', 'w', encoding='utf-8') as f:
    f.write('# 术语索引 (Index)\n\n')
    f.write('本书专业数学与机器学习核心术语中英双语对照及原书页码索引如下（按字母顺序排序）：\n\n')
    
    current_letter = ''
    for term, pages in index_items:
        first_char = term[0].upper()
        if not first_char.isalpha():
            first_char = '#'
        if first_char != current_letter:
            current_letter = first_char
            f.write(f'\n## {current_letter}\n\n')
            
        zh = term_map.get(term, '')
        if not zh:
            # try case-insensitive or stripped
            for k, v in term_map.items():
                if k.lower() == term.lower():
                    zh = v
                    break
                    
        if zh:
            f.write(f'- **{term}**（{zh}）, {pages}\n')
        else:
            f.write(f'- **{term}**, {pages}\n')

print(f'Wrote {len(index_items)} index items to 4.Index.md')
