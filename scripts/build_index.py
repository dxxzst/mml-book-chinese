import pymupdf
import re

doc = pymupdf.open(r'E:\需求记录\文档资料\Books\mml-book_printed.pdf')

index_items = []
for pno in range(412, 417):
    page = doc[pno]
    text = page.get_text()
    for line in text.splitlines():
        line = line.strip()
        if not line or line in ['Index'] or re.match(r'^\d+$', line):
            continue
        if 'Draft (' in line or 'To be published by Cambridge' in line or 'https://mml-book.com' in line or 'c⃝' in line:
            continue
        m = re.match(r'^(.*?),\s*([\d\s,–-]+)$', line)
        if m:
            term, pages = m.group(1).strip(), m.group(2).strip()
            # clean ligatures
            term = term.replace('ﬁ', 'fi').replace('ﬂ', 'fl')
            index_items.append((term, pages))

